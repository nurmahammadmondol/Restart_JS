// 1. Math.min() — সবচেয়ে ছোট সংখ্যা
console.log(Math.min(10, 5, 20, 3));

Output: 3



// 2. Math.round() — কাছাকাছি পূর্ণসংখ্যা
console.log(Math.round(4.6));

Output: 5



// 3. Math.floor() — নিচের পূর্ণসংখ্যা
console.log(Math.floor(4.9));

Output: 4



// 4. Math.ceil() — উপরের পূর্ণসংখ্যা
console.log(Math.ceil(4.1));

Output: 5



// 5. Math.random() — র‍্যান্ডম সংখ্যা
console.log(Math.random());

Output: 0.7352 





