Math.min()	// সবচেয়ে ছোট সংখ্যা
Math.max()	// সবচেয়ে বড় সংখ্যা
Math.round()	// কাছাকাছি পূর্ণসংখ্যা
Math.floor()	// নিচের পূর্ণসংখ্যা
Math.ceil()	// উপরের পূর্ণসংখ্যা
Math.random()	// র‍্যান্ডম সংখ্যা